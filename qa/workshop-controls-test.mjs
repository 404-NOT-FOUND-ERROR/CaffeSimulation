import assert from 'node:assert/strict';
import {freshWorkshop,turnShell,setBasket,brushRim,placePot,setHeat,tickWorkshop,pourCoffee,totalCup,SPEC} from '../workshop-state.mjs';
import {measureWater,measurePowder,reviseBlend} from '../workshop-controls.mjs';
const s=freshWorkshop();assert.ok(measureWater(s,120));assert.equal(s.water,0);
turnShell(s,1);measurePowder(s,18);setBasket(s,true);
measureWater(s,148);assert.equal(s.basketIn,false);assert.equal(s.water,148);assert.ok(setBasket(s,true));
measureWater(s,120);assert.ok(s.events.includes('water-corrected'));assert.equal(s.powder,18);
measurePowder(s,10);assert.equal(s.powder,10);measurePowder(s,18);setBasket(s,true);brushRim(s,200);turnShell(s,-1);placePot(s,true);setHeat(s,2);
for(let i=0;i<200;i++)tickWorkshop(s,.1);
const before={water:s.water,powder:s.powder};assert.ok(measureWater(s,130));assert.ok(measurePowder(s,2));assert.deepEqual({water:s.water,powder:s.powder},before);
setHeat(s,0);placePot(s,false);pourCoffee(s,40,1);assert.equal(s.poured,40);
const solutes=s.pouredSolutes;reviseBlend(s,'milk',230);reviseBlend(s,'water',180);
assert.equal(totalCup(s),SPEC.cupMax);assert.equal(s.cup.milk,230);assert.equal(s.cup.water,80);
reviseBlend(s,'milk',0);assert.equal(s.poured,40);assert.equal(s.pouredSolutes,solutes);assert.equal(s.cup.water,80);
assert.ok(reviseBlend(s,'ice',300));assert.equal(s.cup.ice,230);assert.equal(totalCup(s),SPEC.cupMax);
console.log('PASS: measured preparation, automatic basket removal, overfill correction, hot-state locks, independent blend editing, cup capacity and conserved coffee');
