import assert from 'node:assert/strict';
import {freshWorkshop,turnShell,setBasket,brushRim,placePot,setHeat,tickWorkshop,pourCoffee} from '../workshop-state.mjs';
import {measureWater,measurePowder} from '../workshop-controls.mjs';
import {recipeFromWorkshop,validSession} from '../recipe-workshop-bridge.mjs';
import {restore,snapshot,setAmount,splitCup,round} from '../recipe-state.mjs';

const w=freshWorkshop();turnShell(w,1);measureWater(w,120);measurePowder(w,18);
setBasket(w,true);brushRim(w,200);turnShell(w,-1);placePot(w,true);setHeat(w,1.6);
for(let i=0;i<150;i++)tickWorkshop(w,.1);
assert.throws(()=>recipeFromWorkshop(w,{session:'one'}),/先关火/);
setHeat(w,0);placePot(w,false);pourCoffee(w,1000,1);
const s=recipeFromWorkshop(w,{session:'one',orderId:'share',ticket:7});
assert.equal(s.orderId,'share');assert.equal(s.ticket,7);assert.equal(s.batches.length,1);
assert.equal(s.batches[0].kind,'brewed');assert.equal(s.batches[0].capacity,round(w.poured));
assert.equal(s.cups[0].amounts.coffee,round(w.poured));assert.deepEqual(s.cups[0].allocations,{'workshop-one':round(w.poured)});
for(const [k,n] of Object.entries(s.cups[0].amounts))if(k!=='coffee')assert.equal(n,0,'no automatic additives');
assert.equal(s.batches[0].record.workshopSession,'one');assert.equal(s.batches[0].record.stop,round(w.stopProgress*100));
assert.ok(s.batches[0].record.history.length>=2);assert.equal(s.batches[0].record.heat,1.6);
setAmount(s,'milk',80);splitCup(s);setAmount(s,'water',50);s.pendingWorkshopSession='two';
const saved=snapshot(s),reloaded=restore(saved);assert.equal(reloaded.pendingWorkshopSession,'two');
assert.deepEqual(reloaded.batches[0].record,s.batches[0].record);
const again=recipeFromWorkshop(w,{session:'one',orderId:'share',previous:saved});
assert.deepEqual(again.cups,s.cups,'returning to the completed brewer must not overwrite recipe');
assert.equal(again.batches.length,1,'returning must not duplicate coffee');
const freelyEdited=snapshot(s);freelyEdited.orderId=null;
const returnedFree=recipeFromWorkshop(w,{session:'one',orderId:'share',previous:freelyEdited});
assert.equal(returnedFree.orderId,null);assert.deepEqual(returnedFree.cups,s.cups,'putting back an order must survive returning to its completed brewer');
const refill=recipeFromWorkshop(w,{session:'two',orderId:'share',previous:saved,preserve:true});
assert.deepEqual(refill.cups,s.cups,'a refill preserves both cups and their allocations');
assert.equal(refill.batches.length,2);assert.equal(refill.batchId,'workshop-two');assert.equal(refill.pendingWorkshopSession,undefined);
const free=recipeFromWorkshop(w,{session:'three',previous:saved});assert.equal(free.orderId,null);assert.equal(free.cups.length,1);
assert.equal(free.batches.length,1);assert.equal(free.cups[0].amounts.milk,0);
assert.throws(()=>recipeFromWorkshop({...w,poured:0},{session:'four'}),/先关火/);
assert.equal(validSession('../x'),false);assert.equal(validSession('a'.repeat(33)),false);
console.log('PASS: original brewer hands actual coffee and order to mixing; no example/default additives; idempotent transfer; refill preserves cups; batch record and pending session survive reload.');
